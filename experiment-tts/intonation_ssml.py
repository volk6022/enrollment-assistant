"""
intonation_ssml.py
Словарь интонационных маркеров + конвертер размеченного текста в Silero SSML.

Идея: LLM во время генерации вставляет в текст короткие маркеры
вида [q], [exc], [pause:long] и т.п. — это дешевле по токенам и
надёжнее, чем просить модель писать валидный XML/SSML напрямую.
Этот модуль конвертирует такую разметку в SSML, который понимает
Silero (apply_tts(ssml_text=...)).

Если LLM маркер не проставила (или вы используете эту функцию поверх
текста, который LLM не размечала) — есть фоллбек по пунктуации,
он оборачивает ЦЕЛОЕ предложение в prosody, а не куски внутри него
(Silero/SSML в целом ведёт себя стабильнее, если prosody не рвёт
предложение на середине).
"""

import re
from xml.sax.saxutils import escape

# ---------------------------------------------------------------------------
# 1. Словарь маркеров для LLM.
#    Ключ — токен, который LLM вставляет в текст.
#    Значение — атрибуты Silero SSML <prosody> либо длительность паузы.
# ---------------------------------------------------------------------------
MARKER_MAP = {
    "[q]":           {"pitch": "high"},                   # вопрос БЕЗ явного "?" (Silero сама разруливает "?")
    "[q_strong]":    {"pitch": "x-high"},                  # риторический/эмоц. вопрос, форсировать сильнее дефолта
    "[exc]":         {"pitch": "x-high", "rate": "fast"},  # восклицание
    "[calm]":        {"pitch": "low", "rate": "slow"},     # спокойный/грустный тон
    "[fast]":        {"rate": "fast"},
    "[slow]":        {"rate": "x-slow"},
    "[emp]":         {"pitch": "high", "rate": "slow"},    # смысловой акцент
    "[pause:short]": {"break_ms": 150},
    "[pause]":       {"break_ms": 400},
    "[pause:long]":  {"break_ms": 800},
}

_MARKER_RE = re.compile(r"\[(?:q_strong|q|exc|calm|fast|slow|emp|pause(?::\w+)?)\]")

# ---------------------------------------------------------------------------
# 2. Фоллбек: эвристика по завершающей пунктуации предложения.
#    Применяется, если в предложении нет ни одного маркера из MARKER_MAP.
#
#    Silero v5.5 (v5_5_ru) сама умеет вопросительную интонацию по одиночному
#    "?" (флаг questions=✅ в models.yml) — поэтому одиночный "?" здесь
#    намеренно НЕ трогаем и prosody не навешиваем, модель справится сама.
#    Оставлены только случаи, которые встроенный механизм вряд ли покрывает:
#    усиленный "?!" и растянутое многоточие. "!" тоже оставлен — обычный
#    восклицательный знак Silero, в отличие от "?", отдельным флагом не
#    выделен, так что подстраховка не помешает.
# ---------------------------------------------------------------------------
PUNCT_FALLBACK = [
    (re.compile(r"\?!+$"), {"pitch": "x-high", "rate": "fast"}),
    (re.compile(r"!+$"),   {"pitch": "high", "rate": "fast"}),
    (re.compile(r"\.\.\.$|…$"), {"pitch": "low", "rate": "slow"}),
]

DEFAULT_TRAILING_BREAK_MS = 250   # пауза после обычной точки
COMMA_BREAK_MS = 120              # микропауза на запятой (опционально)


def _wrap_prosody(text: str, attrs: dict) -> str:
    """Оборачивает кусок текста в <prosody>, если атрибуты заданы."""
    prosody_attrs = {k: v for k, v in attrs.items() if k in ("pitch", "rate")}
    if not prosody_attrs:
        return escape(text)
    attr_str = " ".join(f'{k}="{v}"' for k, v in prosody_attrs.items())
    return f"<prosody {attr_str}>{escape(text)}</prosody>"


def markers_to_ssml(sentence: str) -> str:
    """
    Конвертирует ОДНО предложение (с маркерами или без) в тело SSML
    (без внешнего <speak>...</speak> — оборачивайте им весь чанк снаружи,
    если склеиваете несколько предложений в один вызов apply_tts).
    """
    if _MARKER_RE.search(sentence):
        parts = _MARKER_RE.split(sentence)
        marks = _MARKER_RE.findall(sentence)
        out = []
        if parts[0].strip():
            out.append(escape(parts[0]))
        for mark, following in zip(marks, parts[1:]):
            attrs = MARKER_MAP[mark]
            if "break_ms" in attrs:
                out.append(f'<break time="{attrs["break_ms"]}ms"/>')
                if following.strip():
                    out.append(escape(following))
            else:
                if following.strip():
                    out.append(_wrap_prosody(following, attrs))
        return "".join(out)

    # фоллбек по пунктуации — оборачиваем предложение целиком
    for pattern, attrs in PUNCT_FALLBACK:
        if pattern.search(sentence.strip()):
            return _wrap_prosody(sentence, attrs)

    return escape(sentence)


def sentence_to_full_ssml(sentence: str, trailing_break_ms: int = DEFAULT_TRAILING_BREAK_MS) -> str:
    """
    Готовый SSML для одного предложения — то, что можно сразу
    подать в model.apply_tts(ssml_text=...).
    """
    body = markers_to_ssml(sentence)
    return f'<speak><p><s>{body}</s></p><break time="{trailing_break_ms}ms"/></speak>'


# ---------------------------------------------------------------------------
# 3. System-prompt заготовка для LLM — учим модель пользоваться маркерами
# ---------------------------------------------------------------------------
LLM_SYSTEM_PROMPT_SNIPPET = """
При генерации текста для озвучки можешь (не обязательно в каждом предложении)
вставлять интонационные маркеры прямо в текст, ПЕРЕД словом/фразой, к которой
они относятся. Не выделяй маркерами середину слова.

Доступные маркеры:
[q]           — вопросительная интонация ДЛЯ ФРАЗ БЕЗ ЗНАКА "?"
                (если в тексте уже стоит "?" — интонация и так будет
                правильной, маркер не нужен)
[q_strong]    — форсировать усиленную вопросительную/риторическую интонацию
                поверх обычной, в том числе при наличии "?"
[exc]         — восклицание
[calm]        — спокойный, тихий, грустный тон
[fast] / [slow] — ускорить / замедлить участок речи
[emp]         — смысловое выделение (акцент)
[pause] / [pause:short] / [pause:long] — пауза (обычная/короткая/длинная)

Маркеры НЕ парные — [emp] действует на весь текст ПОСЛЕ себя, до следующего
маркера или конца предложения. Закрывающих тегов вроде [/emp] нет и быть не должно.

Пример:
"Ты серьёзно? [q] Мы же [emp]точно договаривались на пятницу. [pause:short] Ладно, [calm] разберёмся."

Не злоупотребляй маркерами — 0-2 на предложение обычно достаточно.
"""


# ---------------------------------------------------------------------------
# 4. Пример использования
# ---------------------------------------------------------------------------
if __name__ == "__main__":
    examples = [
        "Ты серьёзно? [q] Мы же [emp]точно договаривались на пятницу.",
        "Погоди... [pause:long] я не понимаю, что произошло.",
        "Это невероятно!",
        "Ты уже поел?",  # одиночный "?" без маркера — теперь идёт как есть, без ручной prosody
        "Обычное повествовательное предложение без маркеров.",
    ]
    for s in examples:
        print(sentence_to_full_ssml(s))
